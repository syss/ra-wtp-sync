# Interactive setup: asks a few questions, writes config.toml + api_key next to
# this script (both git-ignored), runs a dry run and optionally schedules it.
set -euo pipefail
cd "$(dirname "$(readlink -f "$0")")"

ask() {  # ask "Question" "default" -> sets REPLY
  local prompt="$1" def="${2:-}"
  if [ -n "$def" ]; then read -rp "$prompt [$def]: " REPLY; REPLY="${REPLY:-$def}"
  else read -rp "$prompt: " REPLY; fi
}

command -v python3 >/dev/null || { echo "python3 (3.11+) is required"; exit 1; }
python3 -c 'import sys; sys.exit(sys.version_info < (3, 11))' || { echo "Python 3.11+ is required"; exit 1; }

if [ -e config.toml ]; then
  ask "config.toml already exists - overwrite? (y/N)" "N"
  [[ "$REPLY" =~ ^[Yy]$ ]] || { echo "Keeping existing config."; exit 0; }
fi

echo "== RetroAchievements account =="
ask "Your RetroAchievements username"; USERNAME="$REPLY"
[ -n "$USERNAME" ] || { echo "username is required"; exit 1; }
echo "Web API key: https://retroachievements.org/settings  ->  Keys"
read -rsp "Paste your API key (input hidden), then press Enter: " KEY; echo
[ -n "$KEY" ] || { echo "API key is required"; exit 1; }
( umask 077; printf '%s' "$KEY" > api_key )
unset KEY

echo; echo "== Folders =="
ask "ROM library to read from (never modified)" "$HOME/roms"; SRC="$REPLY"
[ -d "$SRC" ] || echo "  (note: $SRC does not exist yet)"
ask "Output folder, e.g. inside your Syncthing folder" "$HOME/Sync/roms-wtp"; DEST="$REPLY"
ask "RetroArch saves folder, to prefer ROMs that already have a save (empty = none)" "$HOME/.config/retroarch/saves"; SAVES="$REPLY"

echo; echo "== Choices =="
echo "Available systems (* = suggested default; 'title' = disc based, large files, matched by game title):"
python3 ./ra_wtp_sync.py --api-key-file api_key --list-consoles 2>/dev/null | sed 's/^/  /' || true
ask "Systems to handle: keys or ids separated by spaces, or 'all' (leave the big disc ones out unless you want them)" "n64 snes nes gb gbc gba megadrive"; CONSOLES="$REPLY"
ask "Preferred languages, in order (de fr es it ja en; empty = none)" "en"; LANGS="$REPLY"
ask "Preferred regions, in order (europe usa japan world; empty = none)" "europe usa"; REGIONS="$REPLY"
ask "Build missing hacks from RetroAchievements' official patches? (Y/n)" "Y"; PATCH="$REPLY"
ask "Also keep games you started but have not beaten? (y/N)" "N"; STARTED="$REPLY"

toml_list() { local out="" w; for w in $1; do out+="\"$w\", "; done; printf '[%s]' "${out%, }"; }
yn() { [[ "$1" =~ ^[Yy]$ ]] && echo true || echo false; }

( umask 077; cat > config.toml <<EOF
# Generated by setup.sh - git-ignored, edit freely (see examples/config.example.toml)
username = "$USERNAME"
api_key_file = "api_key"
src = "$SRC"
dest = "$DEST"
saves = $([ -n "$SAVES" ] && printf '["%s"]' "$SAVES" || printf '[]')
consoles = $(toml_list "$CONSOLES")
include_started = $(yn "$STARTED")
build_patches = $(yn "$PATCH")

[preferences]
order = ["save", "qol", "language", "region", "revision"]
languages = $(toml_list "$LANGS")
regions = $(toml_list "$REGIONS")
EOF
)

echo; echo "Config written to $PWD/config.toml - running a dry run (changes nothing)..."
python3 ./ra_wtp_sync.py --dry-run || { echo "Dry run failed - check config.toml"; exit 1; }

echo
ask "Looks right? Run it for real now (Y/n)" "Y"
[[ "$REPLY" =~ ^[Yy]$ ]] && python3 ./ra_wtp_sync.py

echo
ask "Run it automatically every 30 minutes via cron? (y/N)" "N"
if [[ "$REPLY" =~ ^[Yy]$ ]]; then
  line="7,37 * * * * nice -n 10 python3 $PWD/ra_wtp_sync.py >> $PWD/cron.log 2>&1"
  ( crontab -l 2>/dev/null | grep -vF "$PWD/ra_wtp_sync.py"; echo "$line" ) | crontab -
  echo "Cron entry installed:"; echo "  $line"
fi
echo "Done. Re-run ./ra_wtp_sync.py any time (--dry-run to preview)."
